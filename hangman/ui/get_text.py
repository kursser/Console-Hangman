import ui_text

class UIText:

    def __init__(self):
        self.texts = ui_text


    def get_title(sefl):
        return sefl.texts.title


    def get_instruction(self):
        return self.texts.instruction



    def get_difficulty_selection(self):
        return self.texts.difficulty_selection



    def get_menu(self):
        return self.texts.main_menu
